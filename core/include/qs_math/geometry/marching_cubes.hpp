// ─── Edge vertex interpolation ────────────────────────────────────────────────

[[nodiscard]] inline Vec3f mc_interp(
    const Vec3f& p0, const Vec3f& p1, f32 v0, f32 v1, f32 iso=0.f)
{
    if(std::abs(v0-v1)<1e-8f) return (p0+p1)*0.5f;
    f32 t=(iso-v0)/(v1-v0);
    return p0+(p1-p0)*t;
}

// ─── Marching cubes for one cube ─────────────────────────────────────────────

struct MCVertex { Vec3f pos{}, normal{}; };

inline void mc_cube(
    const Vec3f corners[8], const f32 values[8],
    std::vector<MCVertex>& verts, f32 iso=0.f)
{
    u32 cfg=0;
    for(u32 i=0;i<8;++i) if(values[i]<iso) cfg|=(1u<<i);
    if(cfg==0||cfg==255) return;

    u16 edges=MC_EDGE_TABLE_FULL[cfg];
    Vec3f ev[12];
    static constexpr u32 edge_v[12][2]={{0,1},{1,2},{2,3},{3,0},{4,5},{5,6},{6,7},{7,4},{0,4},{1,5},{2,6},{3,7}};
    for(u32 e=0;e<12;++e)
        if(edges&(1u<<e))
            ev[e]=mc_interp(corners[edge_v[e][0]],corners[edge_v[e][1]],
                             values[edge_v[e][0]],values[edge_v[e][1]],iso);

    for(u32 i=0;MC_TRI_TABLE[cfg][i]!=-1;i+=3){
        Vec3f a=ev[MC_TRI_TABLE[cfg][i+0]];
        Vec3f b=ev[MC_TRI_TABLE[cfg][i+1]];
        Vec3f c=ev[MC_TRI_TABLE[cfg][i+2]];
        Vec3f n=normalize(cross(b-a,c-a));
        verts.push_back({a,n}); verts.push_back({b,n}); verts.push_back({c,n});
    }
}

