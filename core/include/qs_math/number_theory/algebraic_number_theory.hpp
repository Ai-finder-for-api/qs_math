// ─── Algebraic integer in Q(√d) ───────────────────────────────────────────────
// α = a + b√d, where d is square-free
template<i64 D>
struct AlgInt {
    i64 a{0},b{0};
    [[nodiscard]] constexpr AlgInt operator+(AlgInt o) const noexcept{return{a+o.a,b+o.b};}
    [[nodiscard]] constexpr AlgInt operator-(AlgInt o) const noexcept{return{a-o.a,b-o.b};}
    [[nodiscard]] constexpr AlgInt operator*(AlgInt o) const noexcept{return{a*o.a+D*b*o.b,a*o.b+b*o.a};}
    [[nodiscard]] constexpr AlgInt operator-()         const noexcept{return{-a,-b};}
    [[nodiscard]] constexpr i64    norm()   const noexcept{return a*a-D*b*b;}
    [[nodiscard]] constexpr i64    trace()  const noexcept{return 2*a;}
    [[nodiscard]] constexpr AlgInt conj()   const noexcept{return{a,-b};}
    [[nodiscard]] constexpr bool   operator==(AlgInt o) const noexcept{return a==o.a&&b==o.b;}
    [[nodiscard]] constexpr bool   is_unit() const noexcept{i64 n=norm();return n==1||n==-1;}

    // Integer part (round toward zero)
    [[nodiscard]] constexpr AlgInt div(AlgInt o) const noexcept {
        i64 no=o.norm(); if(!no) return {};
        // α/β = α*β̄/N(β)
        AlgInt num=(*this)*o.conj();
        return{num.a/no,num.b/no};
    }
    [[nodiscard]] constexpr AlgInt mod(AlgInt o) const noexcept {
        return (*this)-o*div(o);
    }
};

// ─── Euclidean algorithm in Z[√d] (when Euclidean) ────────────────────────────
template<i64 D>
[[nodiscard]] constexpr AlgInt<D> alg_gcd(AlgInt<D> a, AlgInt<D> b) noexcept {
    while(b.norm()!=0){AlgInt<D> t=a.mod(b);a=b;b=t;}
    return a;
}

// ─── Ring of integers Z[√d] vs Z[(1+√d)/2] ────────────────────────────────────
// d≡1 mod 4: ring of integers is Z[(1+√d)/2], disc=-d for d<0
// Otherwise: ring of integers is Z[√d], disc=4d
[[nodiscard]] constexpr i64 fundamental_discriminant(i64 d) noexcept {
    return (d%4==1)?d:4*d;
}

// ─── Ideal in Z[√d] (principal ideal, generated by α) ────────────────────────
template<i64 D, int N>
struct Ideal {
    std::array<AlgInt<D>,N> gens{};
    int n{0};

    constexpr void add(AlgInt<D> g) noexcept { if(n<N) gens[n++]=g; }

    // Norm of ideal: |Z[√d]/I|
    [[nodiscard]] constexpr i64 norm() const noexcept {
        if(n==0) return 0;
        if(n==1) return std::abs(gens[0].norm());
        // Two-generator: norm = gcd of norms (simplified)
        i64 g=std::abs(gens[0].norm());
        for(int i=1;i<n;++i){i64 v=std::abs(gens[i].norm());while(v){i64 t=g%v;g=v;v=t;}}
        return g;
    }

    [[nodiscard]] constexpr bool is_principal() const noexcept { return n==1; }
};

// ─── Minkowski bound ──────────────────────────────────────────────────────────
// Every ideal class contains an ideal with norm ≤ M
// M = (4/π)^{r2} * (n!/n^n) * sqrt(|disc|)
[[nodiscard]] constexpr f64 minkowski_bound(i64 disc, int degree=2, int r2=1) noexcept {
    f64 fac=1; for(int i=1;i<=degree;++i) fac*=i;
    return (std::pow(4.0/3.14159265358979323846,r2)*fac/std::pow(f64(degree),degree))
           *std::sqrt(std::abs(f64(disc)));
}

// ─── Class number (imaginary quadratic, Dirichlet class number formula) ───────
// For d<0, Hurwitz formula for class number h
[[nodiscard]] constexpr i64 class_number_imag_quad(i64 d) noexcept {
    // Count reduced forms ax²+bxy+cy² with b²-4ac=d, |b|≤a≤c
    if(d>=0||d%4!=0&&d%4!=1) return 0;
    i64 h=0;
    i64 limit=(i64)std::sqrt(std::abs(f64(d))/3.0)+1;
    for(i64 b=0;b<=limit;++b) {
        if((d-b*b)%4!=0) continue;
        i64 ac=(b*b-d)/4;
        for(i64 a=b>0?b:1;a*a<=ac;++a) {
            if(ac%a!=0) continue;
            i64 c=ac/a;
            bool reduced=( a<c||(a==c&&b>=0)) && b>=0;
            if(!reduced) continue;
            if(a==b||a==c||b==0) h+=1; else h+=2; // boundary forms count once
        }
    }
    return h;
}

// ─── Ramification index and inertia degree ────────────────────────────────────
// For prime p in Z[√d]: how does (p) factor?
enum class PrimeSplitting { Ramified, Split, Inert };

[[nodiscard]] constexpr PrimeSplitting prime_splitting_quad(i64 d, i64 p) noexcept {
    // Legendre symbol (d/p)
    if(d%p==0) return PrimeSplitting::Ramified;
    // Compute Legendre symbol
    i64 sym=1,a=d%p; if(a<0)a+=p;
    // Euler criterion: a^{(p-1)/2} mod p
    i64 e=(p-1)/2,r=1,base=a;
    while(e>0){if(e&1)r=r*base%p;base=base*base%p;e>>=1;}
    if(r==p-1) return PrimeSplitting::Inert;
    return PrimeSplitting::Split;
}

// ─── p-adic embedding ─────────────────────────────────────────────────────────
// |α|_p = p^{-v_p(N(α))/[K:Q]}
template<i64 D>
[[nodiscard]] constexpr f64 alg_p_adic_norm(AlgInt<D> alpha, i64 p) noexcept {
    i64 n=std::abs(alpha.norm());
    if(n==0) return 0;
    i64 v=0; while(n%p==0){++v;n/=p;}
    return std::pow(f64(p),-f64(v)/2.0);
}

// ─── Units in Z[√d] (Pell equation) ──────────────────────────────────────────
// Fundamental unit via continued fraction
template<i64 D>
[[nodiscard]] constexpr AlgInt<D> fundamental_unit() noexcept {
    if constexpr(D<=0) return{1,0}; // imaginary: only ±1, ±i
    // Use Pell equation solver
    i64 a0=(i64)std::sqrt(f64(D));
    if(a0*a0==D) return{1,0}; // perfect square
    i64 m=0,d=1,a=a0;
    i64 p0=1,p1=a0,q0=0,q1=1;
    for(int iter=0;iter<1000;++iter) {
        m=d*a-m; d=(D-m*m)/d; a=(a0+m)/d;
        i64 p2=a*p1+p0,q2=a*q1+q0;
        AlgInt<D> u{p2,q2};
        if(u.norm()==1||u.norm()==-1) return u;
        p0=p1;p1=p2;q0=q1;q1=q2;
    }
    return{1,0};
}

// ─── Algebraic integer minimal polynomial ─────────────────────────────────────
// For a+b√d: min poly = x² - 2ax + (a²-db²)
[[nodiscard]] constexpr std::array<i64,3> min_poly_quad(i64 a, i64 b, i64 d) noexcept {
    return{a*a-d*b*b,-2*a,1}; // c₀ + c₁x + c₂x²
}

// ─── Euler product for Dedekind zeta (partial) ────────────────────────────────
// ζ_K(s) = ∏_p (1-N(p)^{-s})^{-1} over prime ideals
[[nodiscard]] constexpr f64 dedekind_zeta_partial(i64 d, f64 s, int terms=50) noexcept {
    f64 z=1;
    i64 p=2;
    for(int i=0;i<terms;++i,p=next_prime(p)) {
        switch(prime_splitting_quad(d,p)) {
            case PrimeSplitting::Split:
                z/=(1-std::pow(f64(p),-s))*(1-std::pow(f64(p),-s)); break;
            case PrimeSplitting::Inert:
                z/=(1-std::pow(f64(p*p),-s)); break;
            case PrimeSplitting::Ramified:
                z/=(1-std::pow(f64(p),-s)); break;
        }
    }
    return z;
}

// ─── Lattice in number field (for LLL-based algorithms) ───────────────────────
template<int N>
struct NumberFieldLattice {
    std::array<std::array<f64,N>,N> basis{};
    f64 det{0};

    [[nodiscard]] constexpr f64 gram_det() const noexcept {
        // Gram matrix det = det(B)²
        std::array<std::array<f64,N>,N> G{};
        for(int i=0;i<N;++i) for(int j=0;j<N;++j)
            for(int k=0;k<N;++k) G[i][j]+=basis[i][k]*basis[j][k];
        // 2×2 det
        if constexpr(N==2) return G[0][0]*G[1][1]-G[0][1]*G[1][0];
        return 0; // general: use LU
    }

    // Hermite normal form (column HNF via column reduction)
    [[nodiscard]] constexpr std::array<std::array<i64,N>,N> hnf(
        std::array<std::array<i64,N>,N> M) const noexcept
    {
        for(int k=N-1;k>=0;--k) {
            // Find pivot in row k
            int p=-1;
            for(int j=k;j<N;++j) if(M[k][j]){p=j;break;}
            if(p<0) continue;
            if(p!=k) for(int i=0;i<N;++i) std::swap(M[i][p],M[i][k]);
            if(M[k][k]<0) for(int i=0;i<N;++i) M[i][k]=-M[i][k];
            // Eliminate
            for(int j=0;j<k;++j) {
                i64 q=M[k][j]/M[k][k];
                for(int i=0;i<N;++i) M[i][j]-=q*M[i][k];
            }
        }
        return M;
    }
};
