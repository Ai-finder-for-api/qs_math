// ─── Group axioms (runtime-checkable concepts) ────────────────────────────────

// A group is a set G with binary operation * satisfying:
//   1. Closure:      a,b in G => a*b in G
//   2. Associativity: (a*b)*c = a*(b*c)
//   3. Identity:     exists e: e*a = a*e = a
//   4. Inverse:      exists a^-1: a*a^-1 = a^-1*a = e

template<typename G>
concept GroupElement = requires(G a, G b) {
    { a * b } -> std::convertible_to<G>;
    { a == b } -> std::convertible_to<bool>;
};

// Finite group represented by Cayley table
struct FiniteGroup {
    u32 order{};
    std::vector<u32> cayley; // cayley[a * order + b] = a*b
    u32 identity{0};
    std::vector<u32> inverses;
    std::string name{};

    void set_order(u32 n){
        order=n; cayley.assign(n*n,0); inverses.assign(n,0);}

    [[nodiscard]] u32 op(u32 a, u32 b) const { return cayley[a*order+b]; }

    void compute_inverses(){
        for(u32 a=0;a<order;++a)
            for(u32 b=0;b<order;++b)
                if(op(a,b)==identity){inverses[a]=b;break;}
    }

    [[nodiscard]] bool verify_associativity() const {
        for(u32 a=0;a<order;++a)
        for(u32 b=0;b<order;++b)
        for(u32 c=0;c<order;++c)
            if(op(op(a,b),c)!=op(a,op(b,c))) return false;
        return true;
    }

    [[nodiscard]] bool is_abelian() const {
        for(u32 a=0;a<order;++a)
        for(u32 b=a+1;b<order;++b)
            if(op(a,b)!=op(b,a)) return false;
        return true;
    }

    [[nodiscard]] u32 element_order(u32 a) const {
        u32 cur=a, ord=1;
        while(cur!=identity&&ord<order*10){cur=op(cur,a);++ord;}
        return cur==identity?ord:0;
    }

    // Subgroup generated by element a
    [[nodiscard]] std::vector<u32> cyclic_subgroup(u32 a) const {
        std::vector<u32> sg={identity};
        u32 cur=a;
        while(cur!=identity){sg.push_back(cur);cur=op(cur,a);}
        return sg;
    }

    // Center Z(G): elements commuting with all others
    [[nodiscard]] std::vector<u32> center() const {
        std::vector<u32> Z;
        for(u32 a=0;a<order;++a){
            bool central=true;
            for(u32 b=0;b<order&&central;++b)
                if(op(a,b)!=op(b,a)) central=false;
            if(central) Z.push_back(a);
        }
        return Z;
    }

    // Conjugacy class of element a
    [[nodiscard]] std::vector<u32> conjugacy_class(u32 a) const {
        std::vector<bool> seen(order,false);
        std::vector<u32> cls;
        for(u32 g=0;g<order;++g){
            u32 conj=op(op(g,a),inverses[g]);
            if(!seen[conj]){seen[conj]=true;cls.push_back(conj);}
        }
        return cls;
    }

    // Lagrange: subgroup order must divide group order
    [[nodiscard]] bool is_subgroup(const std::vector<u32>& H) const {
        if(order%H.size()!=0) return false;
        for(u32 a:H) for(u32 b:H){
            bool found=false;
            u32 prod=op(a,inverses[b]);
            for(u32 h:H) if(h==prod){found=true;break;}
            if(!found) return false;
        }
        return true;
    }

    // Normal subgroup: gHg^-1 = H for all g
    [[nodiscard]] bool is_normal(const std::vector<u32>& H) const {
        for(u32 g=0;g<order;++g){
            for(u32 h:H){
                u32 conj=op(op(g,h),inverses[g]);
                bool found=false;
                for(u32 x:H) if(x==conj){found=true;break;}
                if(!found) return false;
            }
        }
        return true;
    }
};

// ─── Cyclic group Z_n ─────────────────────────────────────────────────────────

[[nodiscard]] inline FiniteGroup make_cyclic_group(u32 n) {
    FiniteGroup G; G.set_order(n); G.name="Z_"+std::to_string(n);
    for(u32 a=0;a<n;++a) for(u32 b=0;b<n;++b) G.cayley[a*n+b]=(a+b)%n;
    G.compute_inverses();
    return G;
}

// Dihedral group D_n (symmetries of regular n-gon), order 2n
[[nodiscard]] inline FiniteGroup make_dihedral_group(u32 n) {
    u32 ord=2*n;
    FiniteGroup G; G.set_order(ord); G.name="D_"+std::to_string(n);
    // Elements: r^0..r^(n-1), s, sr, sr^2, ..., sr^(n-1)
    // r^a * r^b = r^((a+b)%n)
    // r^a * s*r^b = s*r^((b-a+n)%n)
    // s*r^a * r^b = s*r^((a+b)%n)
    // s*r^a * s*r^b = r^((b-a+n)%n)
    for(u32 a=0;a<ord;++a)
    for(u32 b=0;b<ord;++b){
        bool ra=a<n, rb=b<n;
        u32 result;
        if(ra&&rb)       result=(a+b)%n;
        else if(ra&&!rb) result=n+((b-n-a+100*n)%n);
        else if(!ra&&rb) result=n+((a-n+b)%n);
        else             result=((b-n)-(a-n)+100*n)%n;
        G.cayley[a*ord+b]=result;
    }
    G.compute_inverses();
    return G;
}

// Symmetric group S_n (all permutations of n elements)
[[nodiscard]] inline FiniteGroup make_symmetric_group(u32 n) {
    // Generate all permutations
    std::vector<u32> perm(n); std::iota(perm.begin(),perm.end(),0);
    std::vector<std::vector<u32>> perms;
    do perms.push_back(perm); while(std::next_permutation(perm.begin(),perm.end()));

    u32 ord=u32(perms.size());
    FiniteGroup G; G.set_order(ord); G.name="S_"+std::to_string(n);

    // Build cayley table: product of permutations
    auto compose=[&](const std::vector<u32>& a, const std::vector<u32>& b)->std::vector<u32>{
        std::vector<u32> r(n); for(u32 i=0;i<n;++i) r[i]=a[b[i]]; return r;};
    auto find_idx=[&](const std::vector<u32>& p)->u32{
        for(u32 i=0;i<ord;++i) if(perms[i]==p) return i; return 0;};

    for(u32 a=0;a<ord;++a)
    for(u32 b=0;b<ord;++b)
        G.cayley[a*ord+b]=find_idx(compose(perms[a],perms[b]));

    G.compute_inverses();
    return G;
}

// ─── Ring ─────────────────────────────────────────────────────────────────────

// A ring is a set R with:
//   (+, R) is an abelian group
//   (*) is associative and distributes over (+)

struct IntegerRing {
    // Z with standard + and *
    [[nodiscard]] static i64 add(i64 a, i64 b) { return a+b; }
    [[nodiscard]] static i64 mul(i64 a, i64 b) { return a*b; }
    [[nodiscard]] static i64 neg(i64 a)         { return -a; }
    [[nodiscard]] static i64 zero()              { return 0; }
    [[nodiscard]] static i64 one()               { return 1; }
    [[nodiscard]] static bool is_unit(i64 a)     { return a==1||a==-1; }
    [[nodiscard]] static std::optional<i64> inverse(i64 a) {
        if(is_unit(a)) return a; return std::nullopt; }
};

// Z/nZ ring (integers mod n)
struct ZnRing {
    u64 n{};

    [[nodiscard]] u64 add(u64 a, u64 b) const { return (a+b)%n; }
    [[nodiscard]] u64 mul(u64 a, u64 b) const { return (a*b)%n; }  // assumes no overflow for small n
    [[nodiscard]] u64 neg(u64 a)         const { return a==0?0:n-a; }
    [[nodiscard]] u64 zero()             const { return 0; }
    [[nodiscard]] u64 one()              const { return 1; }
    [[nodiscard]] u64 pow(u64 base, u64 exp) const {
        u64 r=1; base%=n;
        while(exp>0){if(exp&1)r=mul(r,base);base=mul(base,base);exp>>=1;}
        return r;
    }
    [[nodiscard]] bool is_field() const { return is_prime_gcd(n); }

private:
    [[nodiscard]] static bool is_prime_gcd(u64 n){
        if(n<2) return false;
        for(u64 i=2;i*i<=n;++i) if(n%i==0) return false;
        return true;
    }
};

// Polynomial ring R[x] over integers
struct PolyRingZ {
    using Poly = std::vector<i64>; // coefficients from degree 0

    [[nodiscard]] static Poly zero() { return {0}; }
    [[nodiscard]] static Poly one()  { return {1}; }

    [[nodiscard]] static Poly add(const Poly& a, const Poly& b){
        Poly r(std::max(a.size(),b.size()),0);
        for(u32 i=0;i<a.size();++i) r[i]+=a[i];
        for(u32 i=0;i<b.size();++i) r[i]+=b[i];
        while(r.size()>1&&r.back()==0) r.pop_back();
        return r;
    }

    [[nodiscard]] static Poly mul(const Poly& a, const Poly& b){
        if(a.empty()||b.empty()) return {0};
        Poly r(a.size()+b.size()-1,0);
        for(u32 i=0;i<a.size();++i)
        for(u32 j=0;j<b.size();++j) r[i+j]+=a[i]*b[j];
        return r;
    }

    [[nodiscard]] static Poly neg(const Poly& a){
        Poly r(a.size()); for(u32 i=0;i<a.size();++i) r[i]=-a[i]; return r;}

    [[nodiscard]] static i64 eval(const Poly& p, i64 x){
        i64 r=0,xpow=1;
        for(auto c:p){r+=c*xpow;xpow*=x;}
        return r;}

    [[nodiscard]] static u32 degree(const Poly& p){
        u32 d=0;
        for(u32 i=0;i<p.size();++i) if(p[i]!=0) d=i;
        return d;}
};

// ─── Field ────────────────────────────────────────────────────────────────────

// A field is a commutative ring where every nonzero element has a multiplicative inverse
struct RationalField {
    struct Q {
        i64 p{0},q{1}; // p/q in lowest terms

        [[nodiscard]] static Q make(i64 num, i64 den){
            if(den==0) return {0,1};
            i64 g=std::gcd(std::abs(num),std::abs(den));
            if(den<0){num=-num;den=-den;}
            return {num/g,den/g};
        }

        [[nodiscard]] Q operator+(const Q& o) const { return make(p*o.q+o.p*q, q*o.q); }
        [[nodiscard]] Q operator-(const Q& o) const { return make(p*o.q-o.p*q, q*o.q); }
        [[nodiscard]] Q operator*(const Q& o) const { return make(p*o.p, q*o.q); }
        [[nodiscard]] Q operator/(const Q& o) const { return make(p*o.q, q*o.p); }
        [[nodiscard]] Q operator-() const { return {-p,q}; }
        [[nodiscard]] bool operator==(const Q& o) const { return p==o.p&&q==o.q; }
        [[nodiscard]] bool operator<(const Q& o) const { return p*o.q<o.p*q; }
        [[nodiscard]] f64 to_f64() const { return f64(p)/f64(q); }
    };

    [[nodiscard]] static Q zero()    { return {0,1}; }
    [[nodiscard]] static Q one()     { return {1,1}; }
    [[nodiscard]] static Q inv(Q a)  { return {a.q,a.p}; }
    [[nodiscard]] static bool is_zero(Q a) { return a.p==0; }
};

// GF(p) — prime field
struct PrimeField {
    u64 p{};

    [[nodiscard]] u64 add(u64 a, u64 b) const { return (a+b)%p; }
    [[nodiscard]] u64 sub(u64 a, u64 b) const { return (a+p-b%p)%p; }
    [[nodiscard]] u64 mul(u64 a, u64 b) const {
        // safe multiply via __int128 for large p
        return u64((__uint128_t(a)*b)%p);
    }
    [[nodiscard]] u64 pow(u64 base, u64 exp) const {
        u64 r=1; base%=p;
        while(exp>0){if(exp&1)r=mul(r,base);base=mul(base,base);exp>>=1;}
        return r;
    }
    [[nodiscard]] u64 inv(u64 a) const { return pow(a,p-2); }
    [[nodiscard]] u64 div(u64 a, u64 b) const { return mul(a,inv(b)); }
    [[nodiscard]] u64 neg(u64 a) const { return (p-a)%p; }
    [[nodiscard]] u64 zero() const { return 0; }
    [[nodiscard]] u64 one()  const { return 1; }
};

// ─── Homomorphisms ────────────────────────────────────────────────────────────

// Group homomorphism: f: G -> H such that f(a*b) = f(a)*f(b)
struct GroupHomomorphism {
    std::vector<u32> map; // map[g] = h for elements of G -> H

    [[nodiscard]] bool verify(const FiniteGroup& G, const FiniteGroup& H) const {
        for(u32 a=0;a<G.order;++a)
        for(u32 b=0;b<G.order;++b){
            u32 lhs=map[G.op(a,b)];
            u32 rhs=H.op(map[a],map[b]);
            if(lhs!=rhs) return false;
        }
        return true;
    }

    [[nodiscard]] std::vector<u32> kernel() const {
        std::vector<u32> ker;
        for(u32 g=0;g<map.size();++g) if(map[g]==0) ker.push_back(g);
        return ker;
    }

    [[nodiscard]] std::vector<u32> image() const {
        std::vector<bool> seen(256,false);
        std::vector<u32> img;
        for(u32 h:map) if(!seen[h]){seen[h]=true;img.push_back(h);}
        return img;
    }

    [[nodiscard]] bool is_injective() const { return kernel().size()==1; }
    [[nodiscard]] bool is_surjective(u32 h_order) const { return image().size()==h_order; }
    [[nodiscard]] bool is_isomorphism(u32 h_order) const { return is_injective()&&is_surjective(h_order); }
};

// ─── Module ───────────────────────────────────────────────────────────────────

// Z-module (abelian group with integer scalar action)
struct ZModule {
    u32 rank{};         // free part rank
    std::vector<u32> torsion; // torsion part orders (for finitely generated)

    // Smith normal form: classify Z-modules via elementary divisors
    [[nodiscard]] std::string structure_theorem() const {
        std::string s="Z^"+std::to_string(rank);
        for(u32 t:torsion) s+=" × Z/"+std::to_string(t);
        return s;
    }
};

// ─── Galois theory basics ─────────────────────────────────────────────────────

// Galois group of a polynomial over Q (finite extensions)
struct GaloisGroup {
    u32 degree{};
    FiniteGroup group;
    bool is_solvable_by_radicals{false};

    // Check solvability: G has subnormal series with abelian factors
    [[nodiscard]] bool check_solvable() const {
        // For degree ≤ 4, always solvable; degree 5+ depends on group
        if(degree<=4) return true;
        // S_5 is not solvable; A_5 is simple and not solvable
        if(group.order==120||group.order==60) return false;
        return true; // simplification
    }

    // Discriminant (determines if Galois group is subgroup of A_n)
    [[nodiscard]] static i64 discriminant_quadratic(i64 a, i64 b, i64 c) {
        return b*b - 4*a*c;
    }

    [[nodiscard]] static i64 discriminant_cubic(i64 p, i64 q) {
        // For x^3 + px + q: -4p^3 - 27q^2
        return -4*p*p*p - 27*q*q;
    }
};

// ─── Category theory basics ───────────────────────────────────────────────────

// Object in a category (type-erased)
struct CategoryObject {
    std::string name{};
    u32 id{};
};

// Morphism between objects
struct Morphism {
    u32 domain{}, codomain{};
    std::string name{};
    std::function<void()> action; // abstract

    [[nodiscard]] bool is_endomorphism() const { return domain==codomain; }
};

// Small category with explicit morphism composition
struct SmallCategory {
    std::vector<CategoryObject> objects;
    std::vector<Morphism> morphisms;
    std::vector<std::vector<u32>> composition; // [f][g] = f∘g morphism id

    u32 add_object(const std::string& name){
        u32 id=u32(objects.size());
        objects.push_back({name,id});
        return id;
    }

    u32 add_morphism(u32 dom, u32 cod, const std::string& name){
        u32 id=u32(morphisms.size());
        morphisms.push_back({dom,cod,name,{}});
        return id;
    }

    // Identity morphism for object o
    [[nodiscard]] std::optional<u32> identity(u32 obj) const {
        for(u32 i=0;i<morphisms.size();++i)
            if(morphisms[i].domain==obj&&morphisms[i].codomain==obj&&morphisms[i].name=="id_"+objects[obj].name)
                return i;
        return std::nullopt;
    }

    // Functor check: preserves composition and identities
    [[nodiscard]] bool verify_functor(const SmallCategory& target, const std::vector<u32>& obj_map, const std::vector<u32>& mor_map) const {
        // Check domain/codomain preservation
        for(u32 f=0;f<morphisms.size();++f){
            u32 tf=mor_map[f];
            if(target.morphisms[tf].domain!=obj_map[morphisms[f].domain]) return false;
            if(target.morphisms[tf].codomain!=obj_map[morphisms[f].codomain]) return false;
        }
        return true;
    }
};

